import type { Metadata } from "next";
import Link from "next/link";
import { LegalPage } from "@/components/legal/LegalPage";
import { cdekCountry, deliveryAreaText } from "@/config/cdek-countries";
import { features } from "@/config/features";
import { PRODUCT, SHOP, SITE, sellerContactsText } from "@/config/site";
import { kitPriceUsd, unitPriceUsd, wholesalePriceUsd } from "@/lib/currency";
import { KIT, WHOLESALE } from "@/config/products";
import { formatPrice } from "@/lib/format";
import { renderPerRequestOnOwnServer } from "@/lib/render-mode";

export const metadata: Metadata = {
  title: "Доставка и оплата",
  description: `Доставка СДЭК и способы оплаты на сайте ${SITE.domain}.`,
  alternates: { canonical: "/delivery" },
};

export default async function DeliveryPage() {
  // Условия зависят от ключей ЮKassa и СДЭК, которые на своём сервере есть только при запуске
  await renderPerRequestOnOwnServer();
  const online = features.payments;
  const robokassa = features.robokassa && !features.robokassaTest;
  const free = features.freeDelivery;
  const countries = features.publicCdekCountries;
  const abroadCodes = countries.filter((c) => c !== "RU");
  const abroad = abroadCodes.map((c) => cdekCountry(c).name);

  return (
    <LegalPage title="Доставка и оплата" edition={SHOP.termsEdition}>
      <h2>{abroad.length ? "Доставка СДЭК — Россия и страны ЕАЭС" : "Доставка по России — СДЭК"}</h2>
      <p>
        Доставляем службой СДЭК до пункта выдачи заказов (ПВЗ) {abroad.length ? deliveryAreaText(countries) : "по всей России"}.
        Страну, город и удобный пункт выдачи вы выбираете прямо в форме заказа — там же сразу видны стоимость и
        ориентировочный срок доставки.
      </p>
      <ul>
        <li>
          <strong>Стоимость:</strong>{" "}
          {free
            ? "для покупателя доставка бесплатная."
            : "рассчитывается автоматически в зависимости от города и количества товара и добавляется к сумме заказа."}
        </li>
        <li>
          <strong>Отправка:</strong> передаём заказ в СДЭК в течение {SHOP.dispatchTime} после{" "}
          {online ? "оплаты" : "подтверждения и оплаты"}.
        </li>
        <li>
          <strong>Срок в пути:</strong> по данным СДЭК для выбранного города — показывается при оформлении.
        </li>
        <li>
          <strong>Отслеживание:</strong> после передачи в СДЭК заказу присваивается номер отправления — его можно
          отслеживать на сайте cdek.ru. Когда посылка поступит в пункт выдачи, СДЭК пришлёт уведомление.
        </li>
        <li>
          <strong>Получение:</strong> в пункте выдачи по номеру заказа или коду из уведомления СДЭК и документу,
          удостоверяющему личность. Проверьте упаковку и товар при получении.
        </li>
      </ul>

      {abroad.length > 0 && (
        <>
          <h2>{abroad.join(", ").replace(/, ([^,]+)$/, " и $1")}</h2>
          <p>
            Заказ оформляется так же, как по России: в форме выберите страну доставки, город и пункт выдачи СДЭК —
            стоимость доставки рассчитается автоматически.
            {robokassa
              ? ` Цена для заказов из-за рубежа — $${unitPriceUsd()} за 1 шт. мела (от ${WHOLESALE.minQty} шт. — $${wholesalePriceUsd()} за шт.) и $${kitPriceUsd()} за подарочный набор, доставка тоже указывается в долларах. Оплата — онлайн при оформлении через Robokassa, в рублях по курсу ЦБ РФ на день заказа: сумму в рублях форма показывает до оплаты.`
              : ` Цена и оплата — в рублях${online ? ", онлайн при оформлении" : ""}.`}
          </p>
          <p>
            {robokassa
              ? "На странице Robokassa можно оплатить картой Visa, Mastercard или UnionPay зарубежного банка, а также российской картой — банк спишет сумму в валюте вашей карты по своему курсу. "
              : ""}
            Телефон можно указать местный или российский. Если карта вашего банка не пройдёт на странице оплаты, заказ
            всё равно сохранится — мы свяжемся с вами и поможем с оплатой.
          </p>
          <p>
            <strong>Условия ввоза.</strong> Правила ввоза посылок определяет страна получателя и может их менять. Если
            при ввозе взимаются пошлины, налоги или сборы, их оплачивает получатель.
            {abroadCodes.some((c) => c === "KZ" || c === "KG") &&
              " Для доставки в Казахстан и Кыргызстан в форме заказа нужно указать ИИН (в Кыргызстане — ПИН) получателя: его требует служба доставки."}
          </p>
        </>
      )}

      <h2>Доставка в другие страны</h2>
      <p>
        Для заказов из других стран выберите в форме «Другая страна» и укажите адрес. Способ, стоимость и срок
        международной доставки мы рассчитаем индивидуально и согласуем с вами до оплаты.
      </p>

      <h2>Оплата</h2>
      {online ? (
        <>
          <p>
            Заказы с доставкой СДЭК оплачиваются онлайн сразу при оформлении — на защищённой платёжной странице сервиса
            ЮKassa (ООО НКО «ЮМани»). Доступные способы:
          </p>
          <ul>
            <li>банковские карты «Мир», Visa, Mastercard, выпущенные российскими банками;</li>
            <li>SberPay, ЮMoney и другие способы — какие именно доступны, ЮKassa покажет на странице оплаты.</li>
          </ul>
          <p>
            Данные карты вводятся только на стороне ЮKassa и продавцу не передаются. Платёжный сервис соответствует
            стандарту безопасности PCI DSS. После оплаты вы вернётесь на сайт и увидите статус заказа.
          </p>
        </>
      ) : (
        <p>
          После заявки мы свяжемся с вами, подтвердим наличие и доставку и пришлём ссылку на онлайн-оплату банковской
          картой. Предоплата до подтверждения заказа не требуется.
        </p>
      )}
      <p>
        Цена — {formatPrice(PRODUCT.price)} за 1 шт. мела (от {WHOLESALE.minQty} шт. в заказе — {formatPrice(WHOLESALE.price)} за шт.),{" "}
        {formatPrice(KIT.price)} за подарочный набор. Итоговая сумма к оплате{free ? "" : " с учётом доставки"}{" "}
        отображается перед оплатой. Кассовый чек в соответствии с 54-ФЗ направляется на электронную почту, указанную в
        заказе.
      </p>

      <h2>Вопросы</h2>
      <p>
        По вопросам доставки и оплаты свяжитесь с нами {sellerContactsText()}, указав номер заказа. Условия возврата — на
        странице <Link href="/returns">«Обмен и возврат»</Link>, полные условия продажи — в{" "}
        <Link href="/oferta">публичной оферте</Link>.
      </p>
    </LegalPage>
  );
}
